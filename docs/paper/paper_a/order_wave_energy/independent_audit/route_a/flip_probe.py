"""Route A instrument: which single-relation flips of a sprinkled order exist?

Generator coordinates are used throughout. This is a diagnostic of the
background order law, not an observer and not a test of any wave.

For a sampled configuration x with causal order C, a *candidate* is an ordered
pair whose single relation can be changed without violating transitivity: a
link (remove it) or a critical pair (add it). The instrument asks, for each
candidate involving a tested event, whether the flipped order is the causal
order of some configuration in the same diamond, and returns that
configuration as a certificate.

Three searches are used, each ending in an exact order comparison:

- single: only one endpoint of the pair moves;
- joint: every event may move (sequential linear programming on the cone
  margins, started at x);
- chain: a Metropolis chain on configurations with order exactly C, started at
  x, which is an exact draw from the conditional law given C. Single searches
  are repeated at its checkpoints.

A success is a certificate. A failure of the joint search is not a proof that
no realisation exists.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np
from scipy.optimize import linprog
from scipy.sparse import csr_matrix

TAN_HALF = math.tan(0.5)
TOTAL = 2.0 * TAN_HALF
SHRINK = 0.1  # fraction-to-boundary floor for every preserved margin
STALL = 0.01  # relative decrease of the target margin that counts as progress
MAX_LP = 40
CLEAR = 1e-9  # every margin of a certificate must exceed this in absolute value


@dataclass(frozen=True)
class Geometry:
    name: str
    dim: int  # spacetime dimension
    tip_p: tuple
    tip_q: tuple

    def log_weight(self, point):
        if self.name == "background_q1":
            m = (point[0] + point[1]) / math.sqrt(2.0)
            return -2.0 * math.log1p((m - TAN_HALF) ** 2)
        return 0.0


BACKGROUND = Geometry(
    "background_q1",
    4,
    (0.0, 0.0, 0.0, 0.0),
    ((TOTAL + 1) / math.sqrt(2.0), (TOTAL - 1) / math.sqrt(2.0), 0.0, 0.0),
)
FLAT2 = Geometry("flat_1p1", 2, (0.0, 0.0), (1.0, 0.0))
GEOMETRIES = {g.name: g for g in (BACKGROUND, FLAT2)}


def sample(geom, n, rng):
    """n events by volume in the diamond, plus the two tips as rows n, n+1."""
    kept, size = [], 0
    while size < n:
        if geom.name == "background_q1":
            # Same law as experiments/positive_control/
            # order_wave_cone_constraints.background_points: density
            # cos(u)^4 = (1 + (m - tan 1/2)^2)^-2 in the (m, v, y) chart.
            values = rng.random((4 * n, 5))
            m, v = values[:, 0] * TOTAL, values[:, 1]
            y = (2 * values[:, 2:4] - 1) * math.sqrt(TOTAL / 2)
            inside = np.sum(y**2, axis=1) < 2 * np.minimum(m * v, (TOTAL - m) * (1 - v))
            accept = inside & (values[:, 4] < (1 + (m - TAN_HALF) ** 2) ** -2.0)
            batch = np.column_stack(
                ((m + v) / math.sqrt(2.0), (m - v) / math.sqrt(2.0), y)
            )[accept]
        else:
            values = rng.random((4 * n, geom.dim))
            t = values[:, 0]
            z = values[:, 1:] - 0.5
            radius = np.linalg.norm(z, axis=1)
            accept = (t > radius) & (1 - t > radius)
            batch = np.column_stack((t, z))[accept]
        kept.append(batch)
        size += len(batch)
    x = np.concatenate(kept)[:n]
    return np.vstack((x, geom.tip_p, geom.tip_q))


def order_matrix(xa):
    """rel[k, ell] is True when event k strictly precedes event ell."""
    dt = xa[None, :, 0] - xa[:, None, 0]
    diff = xa[None, :, 1:] - xa[:, None, 1:]
    return dt > np.sqrt(np.sum(diff * diff, axis=2))


def links_and_critical(rel):
    """Boolean matrices of ordered links and of ordered critical pairs.

    (k, ell) is critical when k and ell are unrelated, every predecessor of k
    precedes ell and every successor of ell succeeds k. Adding k < ell then keeps
    the relation transitive.
    """
    a = rel.astype(np.float32)
    link = rel & ((a @ a) == 0)
    unrelated = ~rel & ~rel.T
    np.fill_diagonal(unrelated, False)
    down = (a.T @ (1 - a)) == 0
    up = ((1 - a) @ a.T) == 0
    return link, unrelated & down & up


def constraint_rows(rel):
    """Irredundant rows (K, L, S): links hold, critical pairs stay unrelated.

    If every link of C is a relation of C' and no critical pair of C is a
    relation of C', then C' = C: C is generated by its links, and any
    unrelated ordered pair (a, b) of C has a critical pair (a', b') with
    a' <= a and b <= b', so a < b in C' would force a' < b' in C'.
    """
    link, crit = links_and_critical(rel)
    lk, ll = np.nonzero(link)
    ck, cl = np.nonzero(crit)
    return (
        np.concatenate((lk, ck)),
        np.concatenate((ll, cl)),
        np.concatenate((np.ones(len(lk)), -np.ones(len(ck)))),
    )


def margins(xa, k, ell):
    """Oriented null margin of k -> ell: positive exactly when k precedes ell."""
    d = xa[ell] - xa[k]
    radius = np.sqrt(np.sum(d[..., 1:] ** 2, axis=-1))
    return d[..., 0] - radius, d[..., 1:], radius


def lp_step(xa, rows, target, sign, column, ncol, rho, kappa, scale):
    """Minimise the linearised target margin inside the trust box.

    rows = (K, L, S): each row keeps S * margin above SHRINK times its
    current value. sign * margin(target) is driven down, to -kappa at most.
    column[e] is the first column of event e, or -1 if e is fixed. Lengths
    are multiplied by `scale` inside the programme so that solver tolerances
    are small against the margins.
    """
    k_all = np.append(rows[0], target[0])
    l_all = np.append(rows[1], target[1])
    s_all = np.append(rows[2], sign)
    m, dz, radius = margins(xa, k_all, l_all)
    if np.any(radius <= 0):
        return None
    grad_l = np.column_stack((np.ones(len(m)), -dz / radius[:, None]))
    width = xa.shape[1]
    row_id = np.repeat(np.arange(len(m)), width)
    offsets = np.tile(np.arange(width), len(m))
    data, ri, ci = [], [], []
    for events, coefficient in ((l_all, 1.0), (k_all, -1.0)):
        base = np.repeat(column[events], width)
        keep = base >= 0
        # row: -(S * grad . xi) <= S * m - floor
        data.append((-coefficient * s_all[:, None] * grad_l).ravel()[keep])
        ri.append(row_id[keep])
        ci.append((base + offsets)[keep])
    matrix = csr_matrix(
        (np.concatenate(data), (np.concatenate(ri), np.concatenate(ci))),
        shape=(len(m), ncol),
    )
    signed = s_all * m
    bound = (1.0 - SHRINK) * signed
    bound[-1] = signed[-1] + kappa  # target: sign * margin >= -kappa
    cost = np.zeros(ncol)
    for event, coefficient in ((target[1], 1.0), (target[0], -1.0)):
        if column[event] >= 0:
            start = column[event]
            cost[start : start + width] += coefficient * sign * grad_l[-1]
    solution = linprog(
        cost,
        A_ub=matrix,
        b_ub=bound * scale,
        bounds=(-rho * scale, rho * scale),
        method="highs",
    )
    if solution.status != 0:
        return None
    step = np.zeros_like(xa)
    movable = np.nonzero(column >= 0)[0]
    step[movable] = solution.x.reshape(len(movable), width) / scale
    return step


def realise_flip(xa, rel, target, movers, rows, scale):
    """Search for a configuration whose order is C with `target` flipped.

    Walks inside the set of configurations with order C, lowering the target
    margin, and crosses when the linear programme allows it. Every accepted
    iterate has order exactly C; a success has order exactly the flipped one,
    with every pinned margin and the flipped margin further than CLEAR from
    zero, so it is an interior point of an open set of realisations.
    """
    k, ell = target
    related = bool(rel[k, ell])
    sign = 1.0 if related else -1.0
    flipped = rel.copy()
    flipped[k, ell] = not related
    column = -np.ones(len(xa), dtype=np.int64)
    column[movers] = xa.shape[1] * np.arange(len(movers))
    ncol = xa.shape[1] * len(movers)
    x = xa.copy()
    start = current = sign * float(margins(x, k, ell)[0])
    rho = max(start, 1.0 / scale)
    rho_max, rho_min, kappa = 4.0 * rho, 1e-4 / scale, 0.1 / scale
    info = {"lp": 0, "accepted": 0, "start": start}
    stalled = 0
    for _ in range(MAX_LP):
        step = lp_step(x, rows, target, sign, column, ncol, rho, kappa, scale)
        info["lp"] += 1
        if step is None:
            break
        candidate = x + step
        order = order_matrix(candidate)
        value = sign * float(margins(candidate, k, ell)[0])
        clear = float(np.min(rows[2] * margins(candidate, rows[0], rows[1])[0]))
        if np.array_equal(order, flipped) and min(-value, clear) > CLEAR:
            moved = np.sqrt(np.sum((candidate - xa) ** 2, axis=1))
            info.update(
                success=True,
                final=value,
                clearance=min(-value, clear),
                max_displacement=float(moved.max()),
                moved_events=int(np.sum(moved > 1e-3 / scale)),
            )
            return candidate, info
        if np.array_equal(order, rel) and clear > CLEAR and value < current:
            stalled = stalled + 1 if current - value < STALL * current else 0
            x, current = candidate, value
            info["accepted"] += 1
            rho = min(1.5 * rho, rho_max)
            if stalled >= 2:
                break
        else:
            rho *= 0.5
            if rho < rho_min:
                break
    info.update(success=False, final=current)
    return None, info


def single_rows(rel, mover, target):
    """Every relation of `mover` with every other event, except the target."""
    others = np.delete(np.arange(len(rel)), mover)
    before = rel[others, mover]
    after = rel[mover, others]
    apart = ~before & ~after
    movers = np.full(len(others), mover)
    k = np.concatenate((others[before], movers[after], others[apart], movers[apart]))
    ell = np.concatenate((movers[before], others[after], movers[apart], others[apart]))
    s = np.concatenate((np.ones(before.sum() + after.sum()), -np.ones(2 * apart.sum())))
    keep = ~((k == target[0]) & (ell == target[1]))
    return k[keep], ell[keep], s[keep]


def joint_rows(rel, base_rows, target):
    """Rows that pin every relation except the target one.

    Union of the irredundant rows of C (`base_rows`) and of C with the target
    flipped, with the target pair itself removed. If they all hold, the order
    is C or the flipped order, according to the target relation alone.
    """
    flipped = rel.copy()
    flipped[target] = not rel[target]
    other = constraint_rows(flipped)
    k = np.concatenate((base_rows[0], other[0]))
    ell = np.concatenate((base_rows[1], other[1]))
    s = np.concatenate((base_rows[2], other[2]))
    keep = ~((k == target[0]) & (ell == target[1]))
    packed = np.unique(np.column_stack((k[keep], ell[keep], s[keep])), axis=0)
    return packed[:, 0].astype(np.int64), packed[:, 1].astype(np.int64), packed[:, 2]


def candidates_of(link, crit, event, n):
    """Ordered candidate pairs involving `event` whose partner is not a tip."""
    out = []
    for kind, matrix in (("link", link), ("critical", crit)):
        for k in np.nonzero(matrix[:n, event])[0]:
            out.append((kind, int(k), event))
        for ell in np.nonzero(matrix[event, :n])[0]:
            out.append((kind, event, int(ell)))
    return out


def single_search(xa, rel, target, event, scale):
    """Flip by moving one endpoint only. Returns 'self', 'partner' or None."""
    partner = target[0] if target[1] == event else target[1]
    for label, mover in (("self", event), ("partner", partner)):
        rows = single_rows(rel, mover, target)
        found, _ = realise_flip(xa, rel, target, np.array([mover]), rows, scale)
        if found is not None:
            return label
    return None


def chain(xa, rel, geom, rng, sweeps):
    """Metropolis line moves on configurations with order exactly `rel`.

    One sweep moves every event once along a uniformly random direction. The
    proposal is uniform on the connected segment of the line on which the
    order is unchanged; the acceptance ratio is the density ratio. The
    stationary law is the conditional law of the configuration given the
    order.
    """
    x = xa.copy()
    n = len(x) - 2
    for _ in range(sweeps):
        for k in rng.permutation(n):
            direction = rng.normal(size=x.shape[1])
            direction /= np.linalg.norm(direction)
            delta = np.delete(x, k, axis=0) - x[k]
            a = direction[0] ** 2 - np.sum(direction[1:] ** 2)
            b = delta[:, 0] * direction[0] - delta[:, 1:] @ direction[1:]
            c = delta[:, 0] ** 2 - np.sum(delta[:, 1:] ** 2, axis=1)
            if abs(a) > 1e-9:
                disc = b * b - a * c
                real = disc >= 0
                root = np.sqrt(disc[real])
                roots = np.concatenate(((b[real] - root) / a, (b[real] + root) / a))
            else:
                roots = c[b != 0] / (2 * b[b != 0])
            upper = roots[roots > 0].min()
            lower = roots[roots < 0].max()
            t = (lower + (upper - lower) * rng.random()) * (1 - 1e-9)
            proposal = x[k] + t * direction
            if math.log(rng.random()) < geom.log_weight(proposal) - geom.log_weight(
                x[k]
            ):
                x[k] = proposal
    if not np.array_equal(order_matrix(x), rel):
        raise RuntimeError("chain left the order cell")
    return x


def probe_order(geom, n, seed, n_events, checkpoints, sweeps_each, second_start):
    """Run the three searches on one sampled order.

    Returns (meta, rows) with one row per candidate of each tested event.
    """
    rng = np.random.default_rng(np.random.SeedSequence([20261124, geom.dim, n, seed]))
    xa = sample(geom, n, rng)
    rel = order_matrix(xa)
    link, crit = links_and_critical(rel)
    base_rows = constraint_rows(rel)
    events = sorted(int(e) for e in rng.choice(n, size=n_events, replace=False))
    rows = []
    for event in events:
        for kind, k, ell in candidates_of(link, crit, event, n):
            target = (k, ell)
            row = {
                "n": n,
                "seed": seed,
                "event": event,
                "kind": kind,
                "k": k,
                "ell": ell,
                "margin": float(margins(xa, k, ell)[0]),
                "single0": single_search(xa, rel, target, event, n),
                "chain_single": [],
            }
            if geom.name == "flat_1p1":
                row["known_1p1"] = truth_1p1(xa, k, ell)
            if row["single0"] is None:
                found, info = realise_flip(
                    xa, rel, target, np.arange(n), joint_rows(rel, base_rows, target), n
                )
                row["joint0"] = found is not None
                row["joint0_info"] = info
            rows.append(row)
    # Chain from the sampled configuration. Every state is a draw from the
    # conditional law given the order, so its single-move flips are
    # certificates found without the joint linear programme.
    state = xa
    drift = []
    for _ in range(checkpoints):
        state = chain(state, rel, geom, rng, sweeps_each)
        drift.append(float(np.sqrt(np.mean(np.sum((state - xa)[:n] ** 2, axis=1)))))
        for row in rows:
            hit = single_search(state, rel, (row["k"], row["ell"]), row["event"], n)
            row["chain_single"].append(hit)
    if second_start:
        for row in rows:
            target = (row["k"], row["ell"])
            if row["chain_single"] and row["chain_single"][-1] is not None:
                continue
            found, info = realise_flip(
                state, rel, target, np.arange(n), joint_rows(rel, base_rows, target), n
            )
            row["joint1"] = found is not None
            row["joint1_info"] = info
    meta = {
        "n": n,
        "seed": seed,
        "geometry": geom.name,
        "events": events,
        "relations": int(rel[:n, :n].sum()),
        "links": int(link[:n, :n].sum()),
        "critical": int(crit[:n, :n].sum()),
        "chain_rms_displacement": drift,
    }
    return meta, rows


def truth_1p1(xa, k, ell):
    """Known answer in 1+1 dimensions.

    A two-dimensional order is the intersection of the two null-coordinate
    rankings. Swapping two events that are adjacent in one ranking changes
    exactly their relation. So a link flips when its ends are adjacent in
    either ranking, and an unrelated pair becomes k < ell when the ranking in
    which it is reversed has them adjacent.
    """
    n = len(xa) - 2
    u = np.argsort(np.argsort(xa[:n, 0] + xa[:n, 1]))
    v = np.argsort(np.argsort(xa[:n, 0] - xa[:n, 1]))
    du, dv = u[ell] - u[k], v[ell] - v[k]
    if du > 0 and dv > 0:
        return bool(du == 1 or dv == 1)
    if du > 0:
        return bool(dv == -1)
    return bool(du == -1)
